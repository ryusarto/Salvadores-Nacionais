import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import crypto from 'node:crypto';
import sharp from 'sharp';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.resolve(process.argv[2] || path.join(repo, 'production/sprites/source/laranjao-v1'));
const manifest = JSON.parse(await fs.readFile(path.join(source, 'manifest.json')));
const proposal = JSON.parse(await fs.readFile(path.join(source, 'perfil-runtime.json')));
const profile = Object.fromEntries(['spriteProfile','spriteScale','spriteStatePhases','spriteRecovery','spriteTurboMoves','spriteStripScale'].map(k=>[k,proposal[k]]));
profile.spriteStatePhases=true;
const final = path.join(repo, 'production/sprites/final');
const sequences = [], effects = [], crops = {};
for (const [group, records, pack] of [
  [sequences, manifest.animations, 'laranjao'], [effects, manifest.effects, 'laranjao-fx']
]) {
  await fs.mkdir(path.join(final, pack), { recursive: true });
  for (const a of records) {
    const input = await fs.readFile(path.join(source, a.file));
    const out = 'production/sprites/final/' + pack + '/' + a.action + '.webp';
    await sharp(input).webp({ lossless: true, effort: 6 }).toFile(path.join(repo, out));
    const { data, info } = await sharp(input).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    const frames = [];
    let l = 500, t = 500, r = 0, b = 0;
    for (let i = 0; i < a.frames; i++) {
      const pixels = Buffer.alloc(500 * 500 * 4); let visible = 0, edge = 0;
      for (let y = 0; y < 500; y++) for (let x = 0; x < 500; x++) {
        const offset = (y * info.width + i * 500 + x) * 4;
        data.copy(pixels, (y * 500 + x) * 4, offset, offset + 4);
        if (data[offset + 3] > 16) {
          visible++; if (x === 0 || y === 0 || x === 499 || y === 499) edge++;
          l = Math.min(l, x); t = Math.min(t, y); r = Math.max(r, x); b = Math.max(b, y);
        }
      }
      if (!visible || edge) throw Error('Empty/clipped frame: ' + a.action + '/' + i);
      frames.push({ index: i, visiblePixels: visible, edgePixels: edge,
        sha256: crypto.createHash('sha256').update(pixels).digest('hex') });
    }
    if (new Set(frames.map(f => f.sha256)).size !== a.frames) throw Error('Duplicate frame: ' + a.action);
    if (group === effects) crops[a.action] = [l - 2, t - 2, r - l + 5, b - t + 5].map(n => n * 768 / 500);
    const bytes = await fs.readFile(path.join(repo, out));
    group.push({ name: a.action, file: out, source: a.file, cell: 500, frames,
      sha256: crypto.createHash('sha256').update(bytes).digest('hex'), bytes: bytes.length });
    console.log(out);
  }
}
const bounds = JSON.parse(await fs.readFile(path.join(source, 'limites-muralha.json')));
const walls = Object.fromEntries(Object.entries(bounds.records).map(([name,record])=>[name,record.frames.map(f=>f.solidRect768)]));
await fs.writeFile(path.join(repo, 'src/data/laranjao-art.js'),
  '// Generated by tools/import-laranjao.mjs from the approved v1 atlases.\n' +
  'export const LARANJAO_SPRITES = ' + JSON.stringify(profile, null, 2) + ';\n' +
  'export const LARANJAO_FX_CROPS = ' + JSON.stringify(crops, null, 2) + ';\n' +
  'export const LARANJAO_WALL_BOUNDS = ' + JSON.stringify(walls, null, 2) + ';\n');
await fs.writeFile(path.join(source, 'runtime-manifest.json'), JSON.stringify({
  character: 'laranjao', version: 1, bodyAnimations: sequences.length, bodyFrames: sequences.length * 6,
  effectAnimations: effects.length, effectFrames: effects.length * 6, alpha: 'true', compression: 'lossless WebP',
  cell: 500, bodyFoot: [250, 456], runtimeProfile: profile, sequences, effects
}, null, 2) + '\n');
console.log(JSON.stringify({ bodyAnimations: sequences.length, effectAnimations: effects.length }));

const uiFolder = path.join(repo, 'production/ui/comic-v1');
const uiPath = path.join(uiFolder, 'manifest.json');
const ui = JSON.parse(await fs.readFile(uiPath));
const portrait = await fs.readFile(path.join(source, 'referencias/retrato.png'));
const meta = await sharp(portrait).metadata();
for (const [kind, image] of [
  ['portrait', sharp(portrait).resize(768, 1024, { fit: 'cover', position: 'north' })],
  ['icon', sharp(await fs.readFile(path.join(source,'ui/icone.png'))) ]
]) {
  const a = ui.assets[kind + '-laranjao'];
  await image.webp({lossless:true,effort:6}).toFile(path.join(uiFolder, a.path));
  const bytes = await fs.readFile(path.join(uiFolder, a.path));
  a.sha256 = crypto.createHash('sha256').update(bytes).digest('hex'); a.bytes = bytes.length; a.provisional = false;
}
await fs.writeFile(uiPath, JSON.stringify(ui, null, 2) + '\n');
console.log('Retrato e ícone atualizados.');
